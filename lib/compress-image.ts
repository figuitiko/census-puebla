// Client-only: relies on createImageBitmap and canvas.
const MAX_SIDE = 1600;
const JPEG_QUALITY = 0.75;

/**
 * Downscales a phone photo to a JPEG (long side <= MAX_SIDE) before upload, to save Blob storage and bandwidth.
 * EXIF is dropped (orientation is baked into the pixels). Returns the ORIGINAL file when it cannot help:
 * the browser cannot decode it (e.g. HEIC in Chrome), canvas fails, or the result is not smaller.
 */
export async function compressImage(file: File): Promise<File> {
  if (!file.type.startsWith("image/")) return file;

  try {
    const bitmap = await createImageBitmap(file, { imageOrientation: "from-image" });
    const scale = Math.min(1, MAX_SIDE / Math.max(bitmap.width, bitmap.height));
    const width = Math.round(bitmap.width * scale);
    const height = Math.round(bitmap.height * scale);

    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext("2d");
    if (!context) return file;
    context.fillStyle = "#fff"; // PNG transparency would turn black in JPEG
    context.fillRect(0, 0, width, height);
    context.drawImage(bitmap, 0, 0, width, height);
    bitmap.close();

    const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, "image/jpeg", JPEG_QUALITY));
    if (!blob || blob.size >= file.size) return file;

    return new File([blob], file.name.replace(/\.[^.]+$/, "") + ".jpg", { type: "image/jpeg", lastModified: file.lastModified });
  } catch {
    return file;
  }
}
